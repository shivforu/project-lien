import { Router } from "express";
import type { Kysely } from "kysely";
import type { Database, PackageStatus } from "@project-lien/db";
import { resolveJurisdictionRule, findStateRule, findCountyRule } from "@project-lien/domain-jurisdiction";
import { renderDocumentHtml, renderHtmlToPdf, checkMarginCompliance, runPreflight, type PreflightResult } from "@project-lien/domain-documents";
import { assertTransition, enqueueJob, recordAuditEvent, IllegalTransitionError } from "@project-lien/domain-workflow";
import { requireRole, type AuthenticatedRequest } from "../auth/middleware.js";
import { asyncHandler } from "../async-handler.js";

// VALIDATING is included alongside the two "fresh" entry points because /resubmit (below)
// deliberately leaves a package in VALIDATING before handing control back to this endpoint
// (its response tells the caller to call preflight next) — see the guarded transition below
// for why VALIDATING doesn't re-trigger an illegal VALIDATING -> VALIDATING self-transition.
const PREFLIGHT_STARTABLE_FROM: PackageStatus[] = ["DRAFT", "PREFLIGHT_FAILED", "VALIDATING"];

/**
 * The package-lifecycle action endpoints (docs/API.md `/releases/:id/{preflight,submit,
 * resubmit,cancel}`, docs/REQUIREMENTS_MATRIX.md #5-8, #11-15, #20-21). Split out of
 * `packages.ts` (which only ever had plain CRUD) because these routes are where Phase
 * 3's document/pre-flight engine, Phase 4's PRIA serializer, and Phase 5's eRecording
 * adapters actually get wired into the package lifecycle for the first time — earlier
 * phases built and unit-tested each engine in isolation but nothing before Phase 12
 * called them from a real request. See docs/DECISIONS.md D17 for the "structural
 * pre-flight only, no signature/notary yet" and "auto-fund escrow from unpaid principal"
 * simplifications this surfaced.
 */
export function createPackageActionsRouter(db: Kysely<Database>): Router {
  const router = Router();

  router.post("/:id/preflight", requireRole("ORG_ADMIN", "OPERATOR"), asyncHandler(async (req: AuthenticatedRequest, res) => {
    const id = req.params.id;
    if (!id) {
      res.status(400).json({ error: { code: "VALIDATION_ERROR", message: "id path parameter is required" } });
      return;
    }
    const pkg = await db
      .selectFrom("recording_packages")
      .selectAll()
      .where("id", "=", id)
      .where("organization_id", "=", req.auth!.organizationId)
      .executeTakeFirst();
    if (!pkg) {
      res.status(404).json({ error: { code: "NOT_FOUND", message: `Package '${id}' not found` } });
      return;
    }
    if (!PREFLIGHT_STARTABLE_FROM.includes(pkg.status)) {
      res.status(409).json({
        error: { code: "ILLEGAL_TRANSITION", message: `Cannot run pre-flight from status '${pkg.status}'` },
      });
      return;
    }

    const [loan, property] = await Promise.all([
      db.selectFrom("loans").selectAll().where("id", "=", pkg.loan_id).executeTakeFirstOrThrow(),
      db.selectFrom("properties").selectAll().where("id", "=", pkg.property_id).executeTakeFirstOrThrow(),
    ]);
    const org = await db.selectFrom("organizations").selectAll().where("id", "=", pkg.organization_id).executeTakeFirstOrThrow();
    const state = await findStateRule(db, pkg.state_code);
    if (!state) {
      res.status(422).json({ error: { code: "UNKNOWN_JURISDICTION", message: `No jurisdiction rule for state '${pkg.state_code}'` } });
      return;
    }
    const county = await findCountyRule(db, pkg.county_fips);
    const resolved = resolveJurisdictionRule(state, county);

    // /resubmit already moved a RESUBMISSION_REQUIRED package to VALIDATING before telling
    // the caller to call this endpoint next — re-running that same transition here would be
    // an illegal VALIDATING -> VALIDATING self-transition, so only perform it when starting
    // from a status that isn't already VALIDATING.
    if (pkg.status !== "VALIDATING") {
      await assertAndTransition(db, pkg.id, pkg.status, "VALIDATING", "Pre-flight started");
    }

    // Render the actual document this package would submit — the same Phase 3 engine
    // used everywhere else, not a fixture standing in for it — so pre-flight's margin
    // check runs against real generated bytes.
    const html = renderDocumentHtml(
      {
        docType: pkg.document_type,
        stateName: state.stateName,
        countyName: property.county_name,
        borrowerName: loan.borrower_name,
        lenderName: org.name, // v1 simplification: no separate lender/servicer entity is modeled yet (docs/DECISIONS.md D17) — the organization stands in for it.
        propertyAddress: `${property.address_line1}, ${property.city}, ${property.state_code} ${property.zip_code}`,
        legalDescription: "See recorded instrument reference for full legal description.",
        originalInstrumentNumber: loan.original_instrument_number,
        originalBook: loan.original_book,
        originalPage: loan.original_page,
        loanAmountCents: loan.unpaid_principal_cents,
        trusteeName: null, // no trustee-capture feature exists yet — see docs/DECISIONS.md D17.
        witnessNames: [],
        packageIdentifier: pkg.package_identifier,
      },
      resolved.topMarginInches,
    );
    const pdfBytes = await renderHtmlToPdf(html);
    const margins = await checkMarginCompliance(pdfBytes, resolved.topMarginInches);

    const preflight: PreflightResult = await runPreflight({
      pdfBytes,
      requiredTopMarginInches: resolved.topMarginInches,
      trusteeRequired: resolved.trusteeRequired,
      trusteeName: null,
      witnessesRequired: resolved.witnessesRequired,
      witnessNames: [],
      vision: null, // signature/notary happen later in the lifecycle — not applicable to this structural gate (docs/DECISIONS.md D17).
      requiredFields: {
        borrowerName: loan.borrower_name,
        propertyAddress: property.address_line1,
        packageIdentifier: pkg.package_identifier,
      },
    });

    const nextStatus: PackageStatus = preflight.passed ? "READY" : "PREFLIGHT_FAILED";
    const rejectionReason = preflight.passed
      ? null
      : preflight.findings.filter((f) => f.severity === "BLOCKING").map((f) => f.message).join("; ");

    await assertAndTransition(db, pkg.id, "VALIDATING", nextStatus, `Pre-flight ${preflight.passed ? "passed" : "failed"}`, {
      findings: preflight.findings,
      pageCount: margins.pages.length,
    });
    if (!preflight.passed) {
      await db.updateTable("recording_packages").set({ rejection_reason: rejectionReason }).where("id", "=", pkg.id).execute();
    }

    await recordAuditEvent(db, {
      organizationId: req.auth!.organizationId,
      actorType: "USER",
      actorUserId: req.auth!.sub,
      action: preflight.passed ? "package.preflight_passed" : "package.preflight_failed",
      entityType: "recording_package",
      entityId: pkg.id,
      details: { findingCount: preflight.findings.length },
    });

    const updated = await db.selectFrom("recording_packages").selectAll().where("id", "=", pkg.id).executeTakeFirstOrThrow();
    res.status(200).json({ data: updated, preflight });
  }));

  router.post("/:id/submit", requireRole("ORG_ADMIN", "OPERATOR"), asyncHandler(async (req: AuthenticatedRequest, res) => {
    const id = req.params.id;
    if (!id) {
      res.status(400).json({ error: { code: "VALIDATION_ERROR", message: "id path parameter is required" } });
      return;
    }
    const pkg = await db
      .selectFrom("recording_packages")
      .selectAll()
      .where("id", "=", id)
      .where("organization_id", "=", req.auth!.organizationId)
      .executeTakeFirst();
    if (!pkg) {
      res.status(404).json({ error: { code: "NOT_FOUND", message: `Package '${id}' not found` } });
      return;
    }
    if (pkg.status !== "READY_TO_SUBMIT") {
      res.status(409).json({
        error: { code: "ILLEGAL_TRANSITION", message: `Cannot submit from status '${pkg.status}' — must be READY_TO_SUBMIT` },
      });
      return;
    }

    // Submission calls a real (mock/sandbox) vendor adapter, which is exactly the kind of
    // slow/fallible external call this project's job queue exists for (docs/DECISIONS.md
    // D3) — so this enqueues a job rather than doing the vendor call inline on the
    // request, matching how POLL_VENDOR_SUBMISSION already works.
    //
    // The idempotency key is scoped to the *submission attempt*, not just the package: a
    // key of `submit-package-${pkg.id}` alone would permanently block every future
    // resubmission of the same package too, since `ON CONFLICT (idempotency_key) DO
    // NOTHING` never expires — a rejected-and-resubmitted package (E2E scenario C) would
    // then never be able to enqueue a second SUBMIT_PACKAGE job at all. Counting existing
    // `vendor_submissions` rows for this package gives each genuinely new attempt its own
    // key, while two rapid-fire requests for the *same* attempt (E2E scenario F) still
    // collide correctly, since neither has created a vendor_submissions row yet.
    const priorAttempts = await db
      .selectFrom("vendor_submissions")
      .select((eb) => eb.fn.countAll<string>().as("count"))
      .where("package_id", "=", pkg.id)
      .executeTakeFirstOrThrow();
    const attemptNumber = Number(priorAttempts.count) + 1;

    const jobId = await enqueueJob(db, {
      packageId: pkg.id,
      jobType: "SUBMIT_PACKAGE",
      payload: { packageId: pkg.id },
      idempotencyKey: `submit-package-${pkg.id}-attempt-${attemptNumber}`,
    });

    await recordAuditEvent(db, {
      organizationId: req.auth!.organizationId,
      actorType: "USER",
      actorUserId: req.auth!.sub,
      action: "package.submit_requested",
      entityType: "recording_package",
      entityId: pkg.id,
    });

    res.status(202).json({ data: { packageId: pkg.id, jobId, status: "SUBMIT_QUEUED" } });
  }));

  router.post("/:id/resubmit", requireRole("ORG_ADMIN", "OPERATOR"), asyncHandler(async (req: AuthenticatedRequest, res) => {
    const id = req.params.id;
    if (!id) {
      res.status(400).json({ error: { code: "VALIDATION_ERROR", message: "id path parameter is required" } });
      return;
    }
    const pkg = await db
      .selectFrom("recording_packages")
      .selectAll()
      .where("id", "=", id)
      .where("organization_id", "=", req.auth!.organizationId)
      .executeTakeFirst();
    if (!pkg) {
      res.status(404).json({ error: { code: "NOT_FOUND", message: `Package '${id}' not found` } });
      return;
    }
    if (pkg.status !== "RESUBMISSION_REQUIRED") {
      res.status(409).json({
        error: { code: "ILLEGAL_TRANSITION", message: `Cannot resubmit from status '${pkg.status}' — must be RESUBMISSION_REQUIRED` },
      });
      return;
    }

    await assertAndTransition(db, pkg.id, "RESUBMISSION_REQUIRED", "VALIDATING", "Resubmission acknowledged — re-running pre-flight");

    await recordAuditEvent(db, {
      organizationId: req.auth!.organizationId,
      actorType: "USER",
      actorUserId: req.auth!.sub,
      action: "package.resubmit_requested",
      entityType: "recording_package",
      entityId: pkg.id,
    });

    const updated = await db.selectFrom("recording_packages").selectAll().where("id", "=", pkg.id).executeTakeFirstOrThrow();
    res.status(200).json({
      data: updated,
      message: "Package moved to VALIDATING — call POST /:id/preflight next to re-run pre-flight checks.",
    });
  }));

  router.post("/:id/cancel", requireRole("ORG_ADMIN", "OPERATOR"), asyncHandler(async (req: AuthenticatedRequest, res) => {
    const id = req.params.id;
    if (!id) {
      res.status(400).json({ error: { code: "VALIDATION_ERROR", message: "id path parameter is required" } });
      return;
    }
    const pkg = await db
      .selectFrom("recording_packages")
      .selectAll()
      .where("id", "=", id)
      .where("organization_id", "=", req.auth!.organizationId)
      .executeTakeFirst();
    if (!pkg) {
      res.status(404).json({ error: { code: "NOT_FOUND", message: `Package '${id}' not found` } });
      return;
    }

    try {
      assertTransition(pkg.status, "CANCELLED");
    } catch (err) {
      if (err instanceof IllegalTransitionError) {
        res.status(409).json({ error: { code: "ILLEGAL_TRANSITION", message: err.message } });
        return;
      }
      throw err;
    }

    await assertAndTransition(db, pkg.id, pkg.status, "CANCELLED", "Cancelled by operator");

    await recordAuditEvent(db, {
      organizationId: req.auth!.organizationId,
      actorType: "USER",
      actorUserId: req.auth!.sub,
      action: "package.cancelled",
      entityType: "recording_package",
      entityId: pkg.id,
    });

    const updated = await db.selectFrom("recording_packages").selectAll().where("id", "=", pkg.id).executeTakeFirstOrThrow();
    res.status(200).json({ data: updated });
  }));

  return router;
}

async function assertAndTransition(
  db: Kysely<Database>,
  packageId: string,
  from: PackageStatus,
  to: PackageStatus,
  reason: string,
  metadata?: unknown,
): Promise<void> {
  assertTransition(from, to);
  await db.updateTable("recording_packages").set({ status: to, updated_at: new Date() }).where("id", "=", packageId).execute();
  await db
    .insertInto("workflow_events")
    .values({
      package_id: packageId,
      from_status: from,
      to_status: to,
      actor: "USER",
      reason,
      metadata: metadata === undefined ? null : JSON.stringify(metadata),
    })
    .execute();
}
